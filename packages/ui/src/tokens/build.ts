/**
 * Generates `src/styles/tokens.css` and the root `DESIGN.md` frontmatter from
 * `tokens.ts`, and verifies contrast.
 *
 *   pnpm --filter @benkyou/ui tokens          write both files
 *   pnpm --filter @benkyou/ui tokens:check    fail if stale or contrast fails
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
	type ColorRole,
	color,
	contrastPairs,
	darkSelectors,
	font,
	layout,
	motion,
	type Oklch,
	type Palette,
	radius,
	shadow,
	type,
	zIndex,
} from "./tokens";

const here = dirname(fileURLToPath(import.meta.url));
const CSS_PATH = resolve(here, "../styles/tokens.css");
const DESIGN_PATH = resolve(here, "../../../../DESIGN.md");
const check = process.argv.includes("--check");

// ---------------------------------------------------------------------------
// Color math: oklch → linear sRGB → hex / relative luminance
// ---------------------------------------------------------------------------

function toLinearSrgb([l, c, h]: Oklch): [number, number, number] {
	const a = c * Math.cos((h * Math.PI) / 180);
	const b = c * Math.sin((h * Math.PI) / 180);
	const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
	const clamp = (x: number) => Math.min(1, Math.max(0, x));
	return [
		clamp(4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_),
		clamp(-1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_),
		clamp(-0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_),
	];
}

function hex(v: Oklch): string {
	const enc = (x: number) =>
		x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
	return `#${toLinearSrgb(v)
		.map((x) =>
			Math.round(enc(x) * 255)
				.toString(16)
				.padStart(2, "0"),
		)
		.join("")}`;
}

function luminance(v: Oklch): number {
	const [r, g, b] = toLinearSrgb(v);
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a: Oklch, b: Oklch): number {
	const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
}

const css = ([l, c, h]: Oklch) =>
	`oklch(${+l.toFixed(3)} ${+c.toFixed(3)} ${+h.toFixed(1)})`;

// ---------------------------------------------------------------------------
// tokens.css
// ---------------------------------------------------------------------------

const roles = Object.keys(color.light) as ColorRole[];
const vars = (p: Palette) =>
	roles.map((r) => `\t--${r}: ${css(p[r])};`).join("\n");

function buildCss(): string {
	const themeColors = roles
		.map((r) => `\t--color-${r}: var(--${r});`)
		.join("\n");
	const typeVars = Object.entries(type)
		.map(
			([name, t]) =>
				`\t--text-${name}: ${t.size};\n` +
				`\t--text-${name}--line-height: ${t.lineHeight};\n` +
				`\t--text-${name}--letter-spacing: ${t.tracking};\n` +
				`\t--text-${name}--font-weight: ${t.weight};`,
		)
		.join("\n");

	return `/* GENERATED by src/tokens/build.ts — do not edit. Change src/tokens/tokens.ts and run \`pnpm --filter @benkyou/ui tokens\`. */

:root {
${vars(color.light)}

\t--radius: ${radius.md};
\t--radius-surface: ${radius.lg};
\t--shadow-raised: ${shadow.raised};
\t--shadow-overlay: ${shadow.overlay};
\t--shadow-floating: var(--shadow-raised);
\t--duration-fast: ${motion.fast};
\t--duration-base: ${motion.base};
${Object.entries(zIndex)
	.map(([k, v]) => `\t--z-${k}: ${v};`)
	.join("\n")}
\t--page-gutter: ${layout.pageMobile};
\t--content-max: ${layout.contentMax};
\t--prose-measure: ${layout.proseMeasure};
}

@media (min-width: 768px) {
\t:root {
\t\t--page-gutter: ${layout.pageDesktop};
\t}
}

${darkSelectors.join(",\n")} {
${vars(color.dark)}
}

@media (prefers-reduced-motion: reduce) {
\t:root {
\t\t--duration-fast: 0ms;
\t\t--duration-base: 0ms;
\t}
}

@theme inline {
${themeColors}

\t--radius-sm: ${radius.sm};
\t--radius-md: ${radius.md};
\t--radius-lg: ${radius.lg};
\t--radius-xl: ${radius.xl};

\t--shadow-raised: var(--shadow-raised);
\t--shadow-overlay: var(--shadow-overlay);

\t--ease-out: ${motion.ease};

\t--font-sans: ${font.sans};
\t--font-serif: ${font.serif};
\t--font-mono: ${font.mono};
\t--font-jp: ${font.jp};

${typeVars}
}
`;
}

// ---------------------------------------------------------------------------
// DESIGN.md frontmatter
// ---------------------------------------------------------------------------

function buildFrontmatter(): string {
	const pick: ColorRole[] = [
		"background",
		"foreground",
		"card",
		"muted",
		"muted-foreground",
		"border",
		"input",
		"primary",
		"primary-foreground",
		"accent",
		"accent-foreground",
		"mark",
		"mark-tint",
		"mark-ink",
		"success",
		"warning",
		"info",
		"destructive",
	];
	const colorLines = (p: Palette) =>
		pick.map((r) => `    ${r}: "${hex(p[r])}" # ${css(p[r])}`).join("\n");
	const typeLines = Object.entries(type)
		.map(
			([k, t]) =>
				`  ${k}: "${t.family} ${t.weight} · ${parseFloat(t.size) * 16}px / ${t.lineHeight}"`,
		)
		.join("\n");
	return `---
# GENERATED from packages/ui/src/tokens/tokens.ts — do not edit by hand.
name: Benkyou
colors:
  light:
${colorLines(color.light)}
  dark:
${colorLines(color.dark)}
typography:
  sans: Inter
  serif: Source Serif 4
  jp: Noto Serif JP (mark and 済 stamp only)
${typeLines}
rounded:
  sm: ${parseFloat(radius.sm) * 16}px
  md: ${parseFloat(radius.md) * 16}px
  lg: ${parseFloat(radius.lg) * 16}px
  xl: ${parseFloat(radius.xl) * 16}px
motion:
  fast: ${motion.fast}
  base: ${motion.base}
  ease: "${motion.ease}"
spacing:
  unit: ${layout.spacingUnit}
  page-mobile: ${layout.pageMobile}
  page-desktop: ${layout.pageDesktop}
  content-max: ${layout.contentMax}
  prose-measure: ${layout.proseMeasure}
---`;
}

function withFrontmatter(doc: string, fm: string): string {
	const match = doc.match(/^---\n[\s\S]*?\n---/);
	if (!match) throw new Error("DESIGN.md has no frontmatter block");
	return fm + doc.slice(match[0].length);
}

// ---------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------

const failures: string[] = [];

for (const [theme, palette] of Object.entries(color)) {
	for (const [fg, bg, min] of contrastPairs) {
		const ratio = contrast(palette[fg], palette[bg]);
		if (ratio < min) {
			failures.push(
				`${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`,
			);
		}
	}
}

const nextCss = buildCss();
const currentDesign = readFileSync(DESIGN_PATH, "utf8");
const nextDesign = withFrontmatter(currentDesign, buildFrontmatter());

if (check) {
	let currentCss = "";
	try {
		currentCss = readFileSync(CSS_PATH, "utf8");
	} catch {}
	if (currentCss !== nextCss) failures.push("src/styles/tokens.css is stale");
	if (currentDesign !== nextDesign)
		failures.push("DESIGN.md frontmatter is stale");
} else {
	writeFileSync(CSS_PATH, nextCss);
	writeFileSync(DESIGN_PATH, nextDesign);
	console.log("Wrote src/styles/tokens.css and DESIGN.md frontmatter");
}

if (failures.length) {
	console.error(`Token check failed:\n  - ${failures.join("\n  - ")}`);
	if (check || failures.some((f) => f.includes(":1"))) {
		console.error("Run `pnpm --filter @benkyou/ui tokens` after fixing.");
		process.exit(1);
	}
}
